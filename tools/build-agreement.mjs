/**
 * Measure how often two systems point the same way by chance.
 *
 * This is the number the whole integration rests on. Five systems produce five
 * times as many statements, and some of them rhyme; the reader supplies the
 * significance. The only honest answer is to say, beside every agreement, how
 * often that agreement happens anyway — and the only way to know that is to
 * count it.
 *
 * Run:  node tools/build-agreement.mjs [samples]
 * Writes app/engine/agreementRates.js. Re-run whenever a projection changes.
 *
 * Built like tools/build-rarity.mjs on purpose: deterministic sample, stamped
 * date, generated file committed. A rate nobody can reproduce is not evidence.
 */

import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { initEphemeris } from '../app/engine/swe.js';
import { allSystems } from '../app/engine/systems.js';
import { comparablePairs, agreementTally, STRUCTURAL } from '../app/engine/agreement.js';
import { sampler } from './random.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SAMPLES = Number(process.argv[2]) || 20000;

await initEphemeris();

const rnd = sampler(20260730);
const pairs = comparablePairs();
const agreed = new Map(pairs.map((p) => [p.key, 0]));
const checked = new Map(pairs.map((p) => [p.key, 0]));
const tallies = new Map();
const marginals = new Map();

for (let i = 0; i < SAMPLES; i += 1) {
  // The same input space the app accepts, including the parts that make a
  // system decline to answer: one record in ten has no time (no ascendant),
  // and one in ten has no latitude (no ascendant either). Sampling only
  // complete records would measure agreement rates for a population of
  // readers that does not exist.
  const input = {
    year: rnd(1930, 2030), month: rnd(1, 12), day: rnd(1, 28),
    hour: rnd(0, 23), minute: rnd(0, 59),
    precision: rnd(0, 9) === 0 ? 'unknown' : 'pm5',
    longitude: 122 + rnd(0, 3200) / 100,
    latitude: rnd(0, 9) === 0 ? null : 24 + rnd(0, 2100) / 100,
    sex: rnd(0, 1) === 0 ? 'male' : 'female',
  };

  const facts = allSystems(input);
  for (const { a, b, key } of pairs) {
    const x = a.of(facts);
    const y = b.of(facts);
    if (x == null || y == null) continue;
    checked.set(key, checked.get(key) + 1);
    if (x === y) agreed.set(key, agreed.get(key) + 1);
    // Marginals, counted only over the births where both answered — the same
    // population the joint rate is counted over, or the comparison below would
    // be between two different groups of people.
    if (!marginals.has(key)) marginals.set(key, { a: new Map(), b: new Map() });
    const m = marginals.get(key);
    m.a.set(x, (m.a.get(x) || 0) + 1);
    m.b.set(y, (m.b.get(y) || 0) + 1);
  }

  const tally = agreementTally(facts);
  const label = `${tally.agreed}/${tally.checked}`;
  tallies.set(label, (tallies.get(label) || 0) + 1);
}

const table = {};
for (const { key } of pairs) {
  const n = checked.get(key);
  // A pair nobody could check has no rate. Writing 0 would read as "this never
  // happens" when it means "this was never asked".
  if (n === 0) continue;

  // What the agreement rate would be if the two systems were unrelated: the
  // sum over shared answers of P(a says it) x P(b says it).
  //
  // This is the number that turns "they agree 20.7% of the time" into a
  // finding. On its own, 20.7% invites the reader to be impressed. Beside an
  // expectation of 20.4% it says plainly that the two systems are telling each
  // other nothing — which is what the app owes anyone it shows five systems to.
  const m = marginals.get(key);
  let independent = 0;
  for (const [value, count] of m.a) {
    independent += (count / n) * ((m.b.get(value) || 0) / n);
  }

  table[key] = {
    observed: Number((agreed.get(key) / n).toFixed(5)),
    independent: Number((independent).toFixed(5)),
    checked: n,
  };
}

const body = `/**
 * How often two systems point the same way, measured over ${SAMPLES.toLocaleString('en-US')} random births.
 *
 * GENERATED by tools/build-agreement.mjs — do not edit by hand, re-run it.
 *
 * Each value is the share of the births **where both systems answered** that
 * they answered the same. The denominator matters: a projection declines on a
 * record it cannot support (no ascendant without a birth time), and counting
 * those as disagreements would understate every rate involving them.
 *
 * Read these as the null hypothesis. An agreement occurring at the rate below
 * is what agreement looks like when it means nothing.
 */

export const AGREEMENT_SAMPLES = ${SAMPLES};

/** JST date these rates were counted on. */
export const AGREEMENT_COUNTED_ON = '${new Date(Date.now() + 9 * 3600 * 1000).toISOString().slice(0, 10)}';

export const AGREEMENT_RATES = ${JSON.stringify(table, null, 2)};

/**
 * Measured rates for a pair, or null when it was never measured.
 *
 * \`observed\` is how often the two agreed. \`independent\` is how often they would
 * have agreed if unrelated, from their own answer distributions. When the two
 * are close, the agreement carries no information, and the reading says so.
 */
export function agreementRate(key) {
  return Object.prototype.hasOwnProperty.call(AGREEMENT_RATES, key) ? AGREEMENT_RATES[key] : null;
}

/**
 * How much an agreement beats chance, as a ratio. 1.0 is exactly chance.
 *
 * Deliberately not dressed up as a p-value: with 20,000 samples almost any
 * difference is "significant", and significance is not the question. The
 * question is whether the lift is large enough for a person to care, and a
 * ratio lets them decide that themselves.
 */
export function lift(key) {
  const r = agreementRate(key);
  return r && r.independent > 0 ? r.observed / r.independent : null;
}
`;

writeFileSync(join(ROOT, 'app/engine/agreementRates.js'), body);

console.log(`measured ${pairs.length} comparable pairs over ${SAMPLES} births\n`);
const rows = Object.entries(table).sort((a, b) => a[1].observed - b[1].observed);
console.log('  実測    無関係なら  倍率');
for (const [key, r] of rows) {
  const flag = STRUCTURAL[key] ? '  ← 独立でない' : '';
  const ratio = (r.observed / r.independent).toFixed(2);
  console.log(`  ${(r.observed * 100).toFixed(1).padStart(5)}%  ${(r.independent * 100).toFixed(1).padStart(8)}%  ${ratio.padStart(5)}x  ${key}${flag}`);
}
console.log('\nいくつ一致したか の分布:');
for (const [label, n] of [...tallies.entries()].sort()) {
  console.log(`  ${label.padStart(5)}  ${(n / SAMPLES * 100).toFixed(1)}%`);
}
console.log('\nwrote app/engine/agreementRates.js');
